/* ============================================================
 * assets.ts — Asset loading with procedural fallbacks
 * Every asset load goes through here. A missing asset must
 * fall back to a procedural version, never crash.
 * ============================================================ */

import * as THREE from 'three';
import { useStore } from '../state/store';
import {
  getProceduralRockTextures,
  getProceduralConcreteTextures,
  getProceduralGratingTextures,
  getProceduralWaterNormal,
} from '../materials/procedural';

const BASE = import.meta.env.BASE_URL;

/** Available assets manifest (generated by scan-assets.mjs) */
let availableAssets: string[] = [];
let manifestLoaded = false;

export async function loadManifest(): Promise<void> {
  if (manifestLoaded) return;
  try {
    const res = await fetch(`${BASE}assets/available.json`);
    if (res.ok) {
      availableAssets = await res.json();
    }
  } catch {
    // No manifest available — all assets will use fallbacks
  }
  manifestLoaded = true;
}

export function isAssetAvailable(path: string): boolean {
  return availableAssets.includes(path);
}

export function getAssetUrl(path: string): string {
  return `${BASE}${path}`;
}

export function getCVUrl(): string {
  return `${BASE}cv/Nishant_Jain_CV.pdf`;
}

export function getProjectImageUrl(slug: string): string | undefined {
  const path = `images/projects/${slug}.jpg`;
  // Always try to return the URL — the component should handle load errors
  return `${BASE}${path}`;
}

export interface PBRMaterialProps {
  map?: THREE.Texture | null;
  normalMap?: THREE.Texture | null;
  roughnessMap?: THREE.Texture | null;
  metalnessMap?: THREE.Texture | null;
  alphaMap?: THREE.Texture | null;
}

/**
 * Returns PBR material textures, with automatic procedural fallbacks.
 * Color space is sRGB for albedo, RepeatWrapping for all maps,
 * with tier-based anisotropy (8 on high, 4 on medium/low).
 */
export function usePBR(name: string): PBRMaterialProps {
  const tier = useStore((state) => state.tier);
  const anisotropy = tier === 'high' ? 8 : 4;

  if (name === 'rock') {
    return getProceduralRockTextures(anisotropy);
  } else if (name === 'concrete') {
    return getProceduralConcreteTextures(anisotropy);
  } else if (name === 'grating') {
    return getProceduralGratingTextures();
  } else if (name === 'water') {
    return {
      normalMap: getProceduralWaterNormal(),
    };
  }

  return {};
}

